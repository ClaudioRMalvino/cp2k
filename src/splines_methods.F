! **************************************************************************************************
!> \brief allocates storage for function table to be interpolated
!>      both x and y are allocated
!> \param spl spline_data structure to be initialized
!> \param nn integer number of datapoints, that the function table will hold
!> \par History
!>      2001-09-21-HAF added this doc entry and changed formatting
!> \author unknown
! **************************************************************************************************
   PURE SUBROUTINE init_splinexy(spl, nn)

      TYPE(spline_data_type), INTENT(INOUT)              :: spl
      INTEGER, INTENT(IN)                                :: nn

      spl%n = nn

      IF (ASSOCIATED(spl%y)) THEN
         DEALLOCATE (spl%y)
         NULLIFY (spl%y)
      END IF

      IF (ASSOCIATED(spl%y2)) THEN
         DEALLOCATE (spl%y2)
         NULLIFY (spl%y2)
      END IF

      ALLOCATE (spl%y(1:nn))
      ALLOCATE (spl%y2(1:nn))

   END SUBROUTINE init_splinexy

! **************************************************************************************************
!> \brief allocates storage for y2 table
!>      calculates y2 table and other spline parameters
!> \param spl spline_data structure to be initialized
!>                       spl%y() must hold the function values
!>                       spl%x() must hold the absissa values in increasing
!>                       order OR if dx (below) is given, spl%x(1) must hold
!>                       the starting (left-most) point.
!> \param dx x(i) are assumed to be x(1)+dx*(i-1)
!>                       (spline evaluations will also be faster)
!>      y1a : (OPTIONAL) if present, the 1-deriv of the left endpoint
!>                       if not present, natural spline condition at this end
!>                       (2-deriv == 0)
!>      y1b : (OPTIONAL) if present, the 1-deriv of the right endpoint
!>                       if not present, natural spline condition at this end
!>                       (2-deriv == 0)
!> \param y1a ...
!> \param y1b ...
!> \par Examples
!>      CALL init_spline(spline,dx=0.1_dp)
!>      CALL init_spline(spline,y1b=0.0_dp)
!>      CALL init_spline(spline,0.1_dp,0.0_dp,0.0_dp)
!> \par History
!>      2001-09-21-HAF added this doc entry and changed formatting
!>      2001-09-24-HAF changed interface and re-written
!> \author unknown
!> \note
!>      if dx is given, the x array will be used as y2 array instead of
!>      allocating a new array. (y2 will become x, and x will be nullified)
! **************************************************************************************************
   PURE SUBROUTINE init_spline(spl, dx, y1a, y1b)

      TYPE(spline_data_type), INTENT(INOUT)              :: spl
      REAL(KIND=dp), INTENT(IN)                          :: dx
      REAL(KIND=dp), INTENT(IN), OPTIONAL                :: y1a, y1b

      INTEGER                                            :: i, n
      REAL(KIND=dp)                                      :: p, s
      REAL(KIND=dp), POINTER                             :: ww(:)

      n = spl%n
      spl%xn = spl%x1 + (n - 1)*dx
      spl%h = dx
      spl%invh = 1.0_dp/dx
      spl%h26 = dx**2/6.0_dp
      ALLOCATE (ww(1:n))
      IF (PRESENT(y1a)) THEN
         spl%y2(1) = -0.5_dp
         ww(1) = 3.0_dp*((spl%y(2) - spl%y(1))/dx - y1a)/dx
      ELSE
         spl%y2(1) = 0.0_dp
         ww(1) = 0.0_dp
      END IF
      DO i = 2, n - 1
         s = 0.5_dp
         p = 0.5_dp*spl%y2(i - 1) + 2.0_dp
         spl%y2(i) = -0.5_dp/p
         ww(i) = (3.0_dp*(spl%y(i + 1) - 2.0_dp*spl%y(i) + spl%y(i - 1))/(dx*dx) &
                  - 0.5_dp*ww(i - 1))/p
      END DO
      IF (PRESENT(y1b)) THEN
         spl%y2(n) = (3.0_dp*(y1b - (spl%y(n) - spl%y(n - 1))/dx)/dx - &
                      0.5_dp*ww(n - 1))/(0.5_dp*spl%y2(n - 1) + 1.0_dp)
      ELSE
         spl%y2(n) = 0.0_dp
      END IF
      DO i = n - 1, 1, -1
         spl%y2(i) = spl%y2(i)*spl%y2(i + 1) + ww(i)
      END DO
      DEALLOCATE (ww)

   END SUBROUTINE init_spline

! **************************************************************************************************
!> \brief calculates the potential interpolated with splines value at a given point
!>      and the first derivative. Checks included to avoid just segfaulting!!
!> \param spl_p spline_data structure
!> \param xxi absissa value
!> \param y1 1. derivative at xx
!> \param spl_f ...
!> \param logger ...
!> \return ...
!> \par Output
!>      spline interpolated value at xx
!> \par History
!>      2001-09-25-HAF added this doc entry and changed formatting
!> \author unknown
!> \note
!>      the spline MUST have uniform x values and xx MUST be
!>      in the interpolation interval. No checks are done to ensure
!>      either condition.
! **************************************************************************************************
   FUNCTION potential_s(spl_p, xxi, y1, spl_f, logger)
      TYPE(spline_data_p_type), DIMENSION(:), POINTER    :: spl_p
      REAL(KIND=dp), INTENT(IN)                          :: xxi
      REAL(KIND=dp), INTENT(OUT)                         :: y1
      TYPE(spline_factor_type), POINTER                  :: spl_f
      TYPE(cp_logger_type), POINTER                      :: logger
      REAL(KIND=dp)                                      :: potential_s

      REAL(KIND=dp), PARAMETER                           :: f13 = 1.0_dp/3.0_dp

      INTEGER                                            :: i, output_unit
      REAL(KIND=dp)                                      :: a, b, h26, invh, x4, xx, xx0, y2hi, &
                                                            y2lo, yhi, ylo, yy

      xx0 = 1.0_dp/xxi
      xx = spl_f%rscale(1)*xx0
      x4 = xx*xx
      h26 = spl_p(1)%spline_data%h26
      invh = spl_p(1)%spline_data%invh
      IF (xx >= spl_p(1)%spline_data%xn) THEN
         ! In case the value is not on the spline let's print a warning and give the value
         ! for the smaller point available in the spline..
         ! This should happen in very few cases though..
         output_unit = cp_logger_get_default_unit_nr(logger)
         yy = spl_p(1)%spline_data%xn - spl_p(1)%spline_data%h
         WRITE (output_unit, FMT='(/,80("*"),/,"*",1X,"Value of r in Input =",F11.6,'// &
                '" not in the spline range. Using =",F11.6,T80,"*",/,80("*"))') SQRT(1.0_dp/xx), SQRT(1.0_dp/yy)
         xx = yy
      END IF
      i = INT((xx - spl_p(1)%spline_data%x1)*invh + 1)
      a = (spl_p(1)%spline_data%x1 - xx)*invh + REAL(i, kind=dp)
      b = 1.0_dp - a

      ylo = spl_p(1)%spline_data%y(i)
      yhi = spl_p(1)%spline_data%y(i + 1)
      y2lo = spl_p(1)%spline_data%y2(i)
      y2hi = spl_p(1)%spline_data%y2(i + 1)
      potential_s = (a*ylo + b*yhi - ((a + 1.0_dp)*y2lo + (b + 1.0_dp)*y2hi)*a*b*h26)*spl_f%fscale(1)
      y1 = invh*((yhi - ylo) + ((f13 - a*a)*y2lo - (f13 - b*b)*y2hi)*3.0_dp*h26)
      y1 = 2.0_dp*y1*x4*spl_f%dscale(1)

      potential_s = potential_s + spl_f%cutoff
   END FUNCTION potential_s

! **************************************************************************************************
!> \brief calculates the spline value at a given point
!>        (and possibly the first derivative) WITHOUT checks
!>        and without any funny scaling business, or weird
!>        1/x^2 grid assumptions
!>
!> \param spl ...
!> \param xx ...
!> \param y1 ...
!> \return ...
!> \author HAF
! **************************************************************************************************
   FUNCTION spline_value(spl, xx, y1)
      ! Return value
      TYPE(spline_data_type), INTENT(IN)                 :: spl
      REAL(KIND=dp), INTENT(IN)                          :: xx
      REAL(KIND=dp), INTENT(OUT), OPTIONAL               :: y1
      REAL(KIND=dp)                                      :: spline_value

      REAL(KIND=dp), PARAMETER                           :: f13 = 1.0_dp/3.0_dp

      INTEGER                                            :: i
      REAL(KIND=dp)                                      :: a, b, h26, invh, y2hi, y2lo, yhi, ylo

      h26 = spl%h26
      invh = spl%invh
      i = INT((xx - spl%x1)*invh + 1)

      a = (spl%x1 - xx)*invh + REAL(i, kind=dp)
      b = 1.0_dp - a
      ylo = spl%y(i)
      yhi = spl%y(i + 1)
      y2lo = spl%y2(i)
      y2hi = spl%y2(i + 1)
      spline_value = a*ylo + b*yhi - ((a + 1.0_dp)*y2lo + (b + 1.0_dp)*y2hi)*a*b*h26
      IF (PRESENT(y1)) y1 = invh*((yhi - ylo) + &
                                  ((f13 - a*a)*y2lo - (f13 - b*b)*y2hi)*3.0_dp*h26)
   END FUNCTION spline_value

! **************************************************************************************************
!> \brief Initialise a Hermite cubic spline on a uniform grid by precomputing
!>        the per-interval Horner coefficients in spl%coef(4, n-1).
!>
!>        Requires spl%y(1:n), spl%x1, and spl%n to be set on entry (e.g. via
!>        init_splinexy).  For each interval [x_i, x_{i+1}] with
!>        t = (x - x_i)*invh in [0, 1]:
!>            p(t) = a_0 + a_1*t + a_2*t**2 + a_3*t**3
!>        with a_0 = y_i, a_1 = h*y'_i,
!>             a_2 = -3*y_i + 3*y_{i+1} - 2*h*y'_i - h*y'_{i+1},
!>             a_3 =  2*y_i - 2*y_{i+1} +   h*y'_i + h*y'_{i+1}.
!> \param spl   spline_data structure with y and n already populated
!> \param dx    uniform grid spacing
!> \param dydx  first derivatives y'(x_i) at each of the n grid points
!> \date   2026-05-12
!> \author Claudio Malvino (crm98@cam.ac.uk)
! **************************************************************************************************
   SUBROUTINE init_hermite_spline(spl, dx, dydx)

      TYPE(spline_data_type), INTENT(INOUT)              :: spl
      REAL(KIND=dp), INTENT(IN)                          :: dx
      REAL(KIND=dp), DIMENSION(:), INTENT(IN)            :: dydx

      INTEGER                                            :: i
      REAL(KIND=dp)                                      :: m0, m1, ylo, yhi

      CPASSERT(SIZE(dydx) == spl%n)
      spl%h    = dx
      spl%invh = 1.0_dp/dx
      spl%h26  = dx*dx/6.0_dp
      spl%xn   = spl%x1 + REAL(spl%n - 1, KIND=dp)*dx

      IF (ASSOCIATED(spl%coef)) THEN
         DEALLOCATE (spl%coef)
         NULLIFY (spl%coef)
      END IF
      ALLOCATE (spl%coef(4, spl%n - 1))

      DO i = 1, spl%n - 1
         ylo = spl%y(i)
         yhi = spl%y(i + 1)
         m0  = dx*dydx(i)
         m1  = dx*dydx(i + 1)
         spl%coef(1, i) = ylo
         spl%coef(2, i) = m0
         spl%coef(3, i) = -3.0_dp*ylo + 3.0_dp*yhi - 2.0_dp*m0 - m1
         spl%coef(4, i) =  2.0_dp*ylo - 2.0_dp*yhi +        m0 + m1
      END DO

   END SUBROUTINE init_hermite_spline

! **************************************************************************************************
!> \brief Evaluate a Hermite cubic spline at xx in Horner form, returning the
!>        interpolated value and optionally the first derivative.
!>
!>        Caller must ensure xx lies in [spl%x1, spl%xn]; the index is clamped
!>        but the polynomial extrapolates linearly outside the tabulated range.
!>        spl%coef(:, i) must have been populated by init_hermite_spline.
!> \param spl  Hermite spline data
!> \param xx   evaluation point
!> \param y1   (OPTIONAL) first derivative at xx
!> \return     interpolated function value
!> \date   2026-05-12
!> \author Claudio Malvino (crm98@cam.ac.uk)
! **************************************************************************************************
   FUNCTION hermite_spline_value(spl, xx, y1) RESULT(val)

      TYPE(spline_data_type), INTENT(IN)                 :: spl
      REAL(KIND=dp), INTENT(IN)                          :: xx
      REAL(KIND=dp), INTENT(OUT), OPTIONAL               :: y1
      REAL(KIND=dp)                                      :: val

      INTEGER                                            :: i
      REAL(KIND=dp)                                      :: c1, c2, c3, c4, t

      i = INT((xx - spl%x1)*spl%invh) + 1
      i = MAX(1, MIN(i, spl%n - 1))
      t = (xx - (spl%x1 + REAL(i - 1, KIND=dp)*spl%h))*spl%invh

      c1 = spl%coef(1, i)
      c2 = spl%coef(2, i)
      c3 = spl%coef(3, i)
      c4 = spl%coef(4, i)

      val = c1 + t*(c2 + t*(c3 + t*c4))

      IF (PRESENT(y1)) &
         y1 = spl%invh*(c2 + t*(2.0_dp*c3 + t*3.0_dp*c4))

   END FUNCTION hermite_spline_value

! **************************************************************************************************
!> \brief Evaluate a Chebyshev series sum_k c(k) T_k(t), t in [-1,1], by Clenshaw recurrence.
!>        Value only (fast path for energy-only evaluations).
!> \param c   Chebyshev coefficients, indexed 0:n
!> \param t   evaluation point mapped to [-1, 1]
!> \return    series value at t
!> \author Claudio Malvino (crm98@cam.ac.uk)
! **************************************************************************************************
   PURE FUNCTION clenshaw(c, t) RESULT(val)
      REAL(KIND=dp), DIMENSION(0:), INTENT(IN)           :: c
      REAL(KIND=dp), INTENT(IN)                          :: t
      REAL(KIND=dp)                                      :: val

      INTEGER                                            :: j
      REAL(KIND=dp)                                      :: b0, b1, b2, t2

      t2 = 2.0_dp*t
      b1 = 0.0_dp
      b2 = 0.0_dp
      DO j = UBOUND(c, 1), 1, -1
         b0 = t2*b1 - b2 + c(j)
         b2 = b1
         b1 = b0
      END DO
      val = t*b1 - b2 + c(0)
   END FUNCTION clenshaw

! **************************************************************************************************
!> \brief As clenshaw, but also returns the derivative dval/dt of the series (used when a first
!>        derivative is requested). Carrying the derivative through the same recurrence guarantees
!>        the returned slope is the exact analytic derivative of the returned value, so energies and
!>        forces stay mutually consistent.
!> \param c       Chebyshev coefficients, indexed 0:n
!> \param t       evaluation point mapped to [-1, 1]
!> \param val     series value at t
!> \param dvaldt  derivative of the series w.r.t. t at t
!> \author Claudio Malvino (crm98@cam.ac.uk)
! **************************************************************************************************
   PURE SUBROUTINE clenshaw_d(c, t, val, dvaldt)
      REAL(KIND=dp), DIMENSION(0:), INTENT(IN)           :: c
      REAL(KIND=dp), INTENT(IN)                          :: t
      REAL(KIND=dp), INTENT(OUT)                         :: val, dvaldt

      INTEGER                                            :: j
      REAL(KIND=dp)                                      :: b0, b1, b2, db0, db1, db2, t2

      t2 = 2.0_dp*t
      b1 = 0.0_dp; b2 = 0.0_dp
      db1 = 0.0_dp; db2 = 0.0_dp
      DO j = UBOUND(c, 1), 1, -1
         b0  = t2*b1 - b2 + c(j)
         db0 = 2.0_dp*b1 + t2*db1 - db2
         b2 = b1; b1 = b0
         db2 = db1; db1 = db0
      END DO
      val    = t*b1 - b2 + c(0)
      dvaldt = b1 + t*db1 - db2
   END SUBROUTINE clenshaw_d

! **************************************************************************************************
!> \brief Table-free approximation of cos(xx) for xx in [0, pi] via a degree-13 minimax polynomial.
!>        Drop-in replacement for the EXP/COS/TANH Hermite lookup tables: no index search, no
!>        coefficient gather. If y1 is present it returns the exact derivative of the polynomial
!>        (approximately -sin), keeping cutoff-function values and forces consistent.
!> \param xx   argument in [0, pi]
!> \param y1   (OPTIONAL) first derivative d/dxx at xx
!> \return     approximation of cos(xx)
!> \author Claudio Malvino (crm98@cam.ac.uk)
! **************************************************************************************************
   FUNCTION minimax_cos(xx, y1) RESULT(val)
      REAL(KIND=dp), INTENT(IN)                          :: xx
      REAL(KIND=dp), INTENT(OUT), OPTIONAL               :: y1
      REAL(KIND=dp)                                      :: val

      REAL(KIND=dp)                                      :: t, dvaldt

      ! map [0, pi] -> [-1, 1]
      t = (2.0_dp/pi)*xx - 1.0_dp
      IF (PRESENT(y1)) THEN
         CALL clenshaw_d(c_cos, t, val, dvaldt)
         y1 = dvaldt*(2.0_dp/pi)
      ELSE
         val = clenshaw(c_cos, t)
      END IF
   END FUNCTION minimax_cos

! **************************************************************************************************
!> \brief Table-free approximation of tanh(xx) for xx in [0, 1] via a degree-14 minimax polynomial.
!> \param xx   argument in [0, 1]
!> \param y1   (OPTIONAL) first derivative d/dxx at xx
!> \return     approximation of tanh(xx)
!> \author Claudio Malvino (crm98@cam.ac.uk)
! **************************************************************************************************
   FUNCTION minimax_tanh(xx, y1) RESULT(val)
      REAL(KIND=dp), INTENT(IN)                          :: xx
      REAL(KIND=dp), INTENT(OUT), OPTIONAL               :: y1
      REAL(KIND=dp)                                      :: val

      REAL(KIND=dp)                                      :: t, dvaldt

      ! map [0, 1] -> [-1, 1]
      t = 2.0_dp*xx - 1.0_dp
      IF (PRESENT(y1)) THEN
         CALL clenshaw_d(c_tanh, t, val, dvaldt)
         y1 = dvaldt*2.0_dp
      ELSE
         val = clenshaw(c_tanh, t)
      END IF
   END FUNCTION minimax_tanh

! **************************************************************************************************
!> \brief Table-free approximation of exp(xx) via range reduction exp(x) = 2^k * exp(r),
!>        r = x - k*ln2 in [-ln2/2, ln2/2], with exp(r) from a degree-9 minimax polynomial that is
!>        accurate to full RELATIVE precision. 2^k is applied exactly with the SCALE intrinsic, so
!>        unlike a single global fit the tail decays correctly (e.g. exp(-50) is right to all
!>        digits, not just in absolute terms). Since d/dx exp = exp, y1 (if present) equals val.
!> \param xx   argument (any real; physical ACSF inputs are <= 0)
!> \param y1   (OPTIONAL) first derivative d/dxx at xx (== val)
!> \return     approximation of exp(xx)
!> \author Claudio Malvino (crm98@cam.ac.uk)
! **************************************************************************************************
   FUNCTION exp_reduced(xx, y1) RESULT(val)
      REAL(KIND=dp), INTENT(IN)                          :: xx
      REAL(KIND=dp), INTENT(OUT), OPTIONAL               :: y1
      REAL(KIND=dp)                                      :: val

      INTEGER                                            :: k
      REAL(KIND=dp)                                      :: r, t

      k = NINT(xx*inv_ln2)
      r = xx - REAL(k, KIND=dp)*ln2
      ! map r in [-ln2/2, ln2/2] -> [-1, 1]
      t = r*(2.0_dp*inv_ln2)
      val = SCALE(clenshaw(c_exp, t), k)
      IF (PRESENT(y1)) y1 = val
   END FUNCTION exp_reduced

END MODULE splines_methods
